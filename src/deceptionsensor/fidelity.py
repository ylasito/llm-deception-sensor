"""Safe, deterministic *fictional* tool-calling and bounded response emulation.

No model, shell, network or filesystem access. Request content is not echoed.
"""
from __future__ import annotations
import hashlib
import re
from typing import Any

MAX_TOOLS = 16
MAX_MESSAGES = 100
MAX_NAME = 64


def _safe_tool_names(payload: dict) -> list[str]:
    tools = payload.get('tools', [])
    if not isinstance(tools, list):
        return []
    names: list[str] = []
    for entry in tools[:MAX_TOOLS]:
        if not isinstance(entry, dict):
            continue
        function = entry.get('function') if isinstance(entry.get('function'), dict) else entry
        if not isinstance(function, dict):
            continue
        name = function.get('name')
        if isinstance(name, str) and re.fullmatch(r'[A-Za-z][A-Za-z0-9_-]{0,63}', name):
            if name not in names:
                names.append(name)
    return names


def plan(payload: dict) -> dict[str, Any]:
    """Choose a bounded fictional tool call only on explicit tool_choice.

    Auto mode returns a normal message. No content, secret or system prompt is
    reflected into the generated arguments or assistant response.
    """
    messages = payload.get('messages', [])
    if not isinstance(messages, list):
        messages = []
    messages = messages[-MAX_MESSAGES:]
    choice = payload.get('tool_choice', 'auto')
    names = _safe_tool_names(payload)
    chosen: str | None = None
    if names and choice in ('required', 'any'):
        chosen = names[0]
    elif isinstance(choice, dict):
        f = choice.get('function', {})
        named = f.get('name') if isinstance(f, dict) else None
        if isinstance(named, str) and named in names:
            chosen = named
    turn = len(messages)
    # Request content is never included in response or ID derivation.
    if chosen:
        return {'kind': 'tool', 'name': chosen, 'arguments': '{}', 'turn': turn}
    return {'kind': 'text', 'content': 'Ready.', 'turn': turn}


def openai_response(payload: dict, completion_id: str, model: str, created: int) -> tuple[dict, list[dict]]:
    p = plan(payload)
    base = {'id': completion_id, 'created': created, 'model': model}
    def chunk(delta: dict, reason: str | None = None) -> dict:
        return {**base, 'object': 'chat.completion.chunk', 'choices': [{'index': 0, 'delta': delta, 'finish_reason': reason}]}
    if p['kind'] == 'tool':
        # Random IDs are generated by the server. A request can never force execution.
        call_id = 'call_' + hashlib.sha256(completion_id.encode()).hexdigest()[:20]
        call = {'id': call_id, 'type': 'function', 'function': {'name': p['name'], 'arguments': '{}'}}
        message = {'role': 'assistant', 'content': None, 'tool_calls': [call]}
        chunks = [chunk({'role': 'assistant', 'content': None}),
                  chunk({'tool_calls': [{'index': 0, 'id': call_id, 'type': 'function',
                                         'function': {'name': p['name'], 'arguments': ''}}]}),
                  chunk({'tool_calls': [{'index': 0, 'function': {'arguments': '{}'}}]}),
                  chunk({}, 'tool_calls')]
        finish = 'tool_calls'
    else:
        message = {'role': 'assistant', 'content': p['content']}
        chunks = [chunk({'role': 'assistant', 'content': ''}), chunk({'content': p['content']}), chunk({}, 'stop')]
        finish = 'stop'
    result = {**base, 'object': 'chat.completion', 'choices': [{'index': 0, 'message': message, 'finish_reason': finish}],
              'usage': {'prompt_tokens': 0, 'completion_tokens': 1, 'total_tokens': 1}}
    return result, chunks


def ollama_response(payload: dict, model: str, created_at: str, chat: bool) -> dict:
    p = plan(payload) if chat else {'kind': 'text', 'content': 'Ready.'}
    response = {'model': model, 'created_at': created_at, 'done': True, 'done_reason': 'stop',
                'total_duration': 120000000, 'load_duration': 10000000,
                'prompt_eval_count': 0, 'eval_count': 1, 'eval_duration': 10000000}
    if chat:
        if p['kind'] == 'tool':
            response['message'] = {'role': 'assistant', 'content': '',
                                   'tool_calls': [{'function': {'name': p['name'], 'arguments': {}}}]}
        else:
            response['message'] = {'role': 'assistant', 'content': p['content']}
    else:
        response['response'] = p['content']
    return response


def fingerprint(payload: dict) -> dict:
    """Stable small metadata for test correlation, never raw request content."""
    messages = payload.get('messages', [])
    return {'tool_schema_count': len(_safe_tool_names(payload)),
            'conversation_turns': min(len(messages), MAX_MESSAGES) if isinstance(messages, list) else 0,
            'requested_tool_execution': plan(payload)['kind'] == 'tool'}
